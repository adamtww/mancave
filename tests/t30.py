import asyncio
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(executable_path="/usr/bin/google-chrome",args=["--no-sandbox"])
        pg=await b.new_page(viewport={"width":1500,"height":900});errs=[];pg.on("pageerror",lambda e:errs.append(str(e)))
        await pg.goto("file:///home/claude/mancave/index.html");await pg.wait_for_timeout(400)
        P=lambda x,y: pg.evaluate(f"(()=>{{var s=document.querySelector('#svg'),p=s.createSVGPoint();p.x={x};p.y={y};var q=p.matrixTransform(s.getScreenCTM());return [q.x,q.y]}})()")
        R=lambda: pg.evaluate("(r=>[r.name,r.x,r.y,r.w,r.d,!!r.lk,!!r.sz,!!r.ed,r.col||''])(cave.get().items[0])")
        vis=lambda sel: pg.evaluate(f"getComputedStyle(document.querySelector('{sel}')).display")
        await pg.evaluate("(function(){cave.load({lot:{w:100,d:60},items:[]});var u=cave.room('Shop',10,10,20,15);cave.update(u,{lk:true});cave.select(u)})()");await pg.wait_for_timeout(300)
        print("before:",await R())
        await pg.click("#rm-edit");await pg.wait_for_timeout(300)
        h=await pg.evaluate("(()=>{var q=document.querySelector('.hd[data-h=\"se\"]').getBoundingClientRect();return [q.x+q.width/2,q.y+q.height/2]})()")
        z=await P(40,32);await pg.mouse.move(*h);await pg.mouse.down();await pg.mouse.move(*z,steps=6);await pg.mouse.up();await pg.wait_for_timeout(200)
        await pg.click("#cm-sw .sw1[data-c='#5b8bd9']");await pg.wait_for_timeout(100)
        c=await pg.evaluate("(r=>[r.x+r.w/2,r.y+r.d/2])(cave.get().items[0])");await pg.mouse.click(*(await P(*c)));await pg.wait_for_timeout(350)
        await pg.keyboard.press("Control+A");await pg.keyboard.type("Woodshop");await pg.keyboard.press("Enter");await pg.wait_for_timeout(300)
        print("edited:",await R())
        await pg.mouse.click(*(await P(80,50)));await pg.wait_for_timeout(200)
        print("undo btn:",await vis("#cm-un"),"remove btn:",await vis("#cm-rm"))
        await pg.screenshot(path="/home/claude/build/un.png",clip={"x":300,"y":100,"width":900,"height":500})
        await pg.click("#cm-un");await pg.wait_for_timeout(200)
        print("dialog:",await pg.inner_text("#cd-t"),"|",await pg.inner_text("#cd-m"),"|",await pg.inner_text("#cd-yes"))
        await pg.screenshot(path="/home/claude/build/un2.png")
        await pg.click("#cd-no");await pg.wait_for_timeout(150);print("cancel keeps edit:",await R())
        await pg.click("#cm-un");await pg.wait_for_timeout(150);await pg.click("#cd-yes");await pg.wait_for_timeout(250)
        print("reverted:",await R(),"menus:",await pg.evaluate("[document.querySelector('#cmenu').className,document.querySelector('#rmenu').className]"))
        # new room still shows Remove
        await pg.mouse.click(*(await P(70,40)));await pg.wait_for_timeout(200);await pg.mouse.click(*(await P(70,40)));await pg.wait_for_timeout(250)
        print("rooms:",await pg.evaluate("cave.get().items.map(i=>[i.name,!!i.sz])"))
        if await pg.evaluate("document.querySelector('#emenu')&&getComputedStyle(document.querySelector('#emenu')).display!=='none'"): await pg.click("#em-room");await pg.wait_for_timeout(250)
        await pg.mouse.click(*(await P(5,55)));await pg.wait_for_timeout(200)
        print("new room -> undo:",await vis("#cm-un"),"remove:",await vis("#cm-rm"),errs)
        await b.close()
asyncio.run(main())
